/*
Today's challenge is inspired by the release of ChatGPT on November 30, 2022.

Given a string of one or more sentences, determine if it was likely generated by AI using the following rules:

It contains two or more dashes (-).

It contains two or more sets of parenthesis (()). Text can be within the parenthesis.

It contains three or more words with 7 or more letters.

Words are separated by a single space and only consist of letters (A-Z). Don't include punctuation or other non-letters as part of a word.

If the given sentence meets any of the rules above, return "AI", otherwise, return "Human".
*/

function detectAI(text) {
    let dashCheck = getDashCheck(text);
    let paranthesisCheck = getParCheck(text);
    let lenCheck = getLengthCheck(text);

    if(dashCheck === true || paranthesisCheck === true || lenCheck === true){
        return 'AI';
    }
    return 'Human';
}

const getDashCheck = (text) => {
    let count = 0;
    for(let i = 0; i < text.length;i++){
        if(text[i] === '-'){
            count++;
        }
    }
    if(count >= 2){
        return true;
    }
    return false;
}

const getParCheck = (text) => {
    let count = 0;
    for(let i = 0; i <text.length;i++){
        if(text[i] === '(' || text[i] === ')'){
            count++;
        }
    }

    if(count >= 4){
        return true;
    }
    return false;
}

const getLengthCheck = (text) => {
    let arr = text.split(' ');
    //console.log(arr);
    let count = 0;
    let letterRegex = /[a-zA-Z]/;
    for(let i = 0; i < arr.length;i++){
        let word = '';
        for(let j = 0; j < arr[i].length;j++){
            if(arr[i][j].match(letterRegex)){
                word += arr[i][j];
            }
        }
        if(word.length >= 7){ 
            count++;
        }
    }
    if(count >= 3){
        return true;
    }
    return false;
}


console.log(detectAI("The quick brown fox jumped! over the lazy dog."));
console.log(detectAI("The hypersonic brown fox - jumped (over) the lazy dog."));
