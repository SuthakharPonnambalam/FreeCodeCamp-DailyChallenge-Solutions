/*
Given a starting sequence of two numbers, generate a Fibonacci sequence of the specified length.
The Fibonacci sequence is generated by adding the two previous numbers to get the next number in the sequence.
*/

function fibonacciSequence(startSequence, length) {
    let sum = 0;
    let arr = [];
    let first = startSequence[0];
    let second = startSequence[1]
    for(let i = 0;i < length;i++){
        if(i === 0){
            arr.push(first);
        } else if(i === 1){
            arr.push(second);
        } else {
            sum = arr[i-2] + arr[i-1];
            arr.push(sum);
        }
    }
return arr;
}

console.log(fibonacciSequence([0, 1], 20));